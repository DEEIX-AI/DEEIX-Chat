import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, extname, join } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = dirname(dirname(fileURLToPath(import.meta.url)));
const sourceFile = join(rootDir, "node_modules", "modern-screenshot", "dist", "worker.js");
const targetDir = join(rootDir, "public", "vendor", "modern-screenshot");
const manifestFile = join(rootDir, "shared", "generated", "screenshot-worker.ts");
const source = readFileSync(sourceFile);
const hash = createHash("sha256").update(source).digest("hex").slice(0, 12);
const targetName = `worker.${hash}${extname(sourceFile)}`;
const targetFile = join(targetDir, targetName);
const publicPath = `/vendor/modern-screenshot/${targetName}`;
const manifestContent = [
  "// This file is generated by scripts/sync-screenshot-worker.mjs.",
  `export const screenshotWorkerPath = ${JSON.stringify(publicPath)} as const;`,
  "",
].join("\n");
const targetEntries = existsSync(targetDir) ? readdirSync(targetDir) : [];
const isCurrent =
  targetEntries.length === 1 &&
  targetEntries[0] === targetName &&
  existsSync(targetFile) &&
  readFileSync(targetFile).equals(source) &&
  existsSync(manifestFile) &&
  readFileSync(manifestFile, "utf8") === manifestContent;

if (!isCurrent) {
  rmSync(targetDir, { force: true, recursive: true });
  mkdirSync(targetDir, { recursive: true });
  copyFileSync(sourceFile, targetFile);
  mkdirSync(dirname(manifestFile), { recursive: true });
  writeFileSync(manifestFile, manifestContent);
}
