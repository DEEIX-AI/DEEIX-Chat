import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptFile = fileURLToPath(import.meta.url);
const rootDir = dirname(dirname(scriptFile));
const sourceDir = join(rootDir, "node_modules", "@lobehub", "icons-static-svg", "icons");
const targetDir = join(rootDir, "public", "vendor", "lobehub-icons");
const spriteFile = join(targetDir, "__sprite.svg");
const manifestDir = join(rootDir, "shared", "generated");
const manifestFile = join(manifestDir, "lobehub-icon-manifest.ts");
const sourcePackageFile = join(rootDir, "node_modules", "@lobehub", "icons-static-svg", "package.json");
const syncStampFile = join(targetDir, "__sync-version.txt");
const syncVersion = createHash("sha256")
  .update(readFileSync(sourcePackageFile))
  .update(readFileSync(scriptFile))
  .digest("hex");

function titleFromSlug(slug) {
  return slug
    .replace(/-(brand|brand-color|color|text|text-cn)$/u, "")
    .split("-")
    .filter(Boolean)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function buildSpriteSymbol(fileName) {
  const slug = fileName.slice(0, -4);
  const content = readFileSync(join(targetDir, fileName), "utf8");
  const svgMatch = content.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/u);
  if (!svgMatch) {
    throw new Error(`Invalid SVG: ${fileName}`);
  }
  const [, attributes, rawBody] = svgMatch;
  const viewBoxMatch = attributes.match(/\bviewBox=(["'])(.*?)\1/u);
  if (!viewBoxMatch) {
    throw new Error(`SVG missing viewBox: ${fileName}`);
  }
  const body = rawBody
    .replace(/<title\b[^>]*>[\s\S]*?<\/title>/gu, "")
    .trim();
  return `<symbol id="${slug}" viewBox="${viewBoxMatch[2]}">${body}</symbol>`;
}

function hasExactEntries(directory, expectedEntries) {
  if (!existsSync(directory)) {
    return false;
  }

  const actualEntries = readdirSync(directory).sort((left, right) => left.localeCompare(right));
  return (
    actualEntries.length === expectedEntries.length &&
    actualEntries.every((entry, index) => entry === expectedEntries[index])
  );
}

const sourceEntries = readdirSync(sourceDir).sort((left, right) => left.localeCompare(right));
const iconFiles = sourceEntries.filter((name) => name.endsWith(".svg"));
const icons = iconFiles.map((fileName) => {
  const slug = fileName.slice(0, -4);
  return {
    id: slug,
    name: titleFromSlug(slug),
    src: `/vendor/lobehub-icons/${fileName}`,
  };
});
const manifestContent = [
  "// This file is generated by scripts/sync-lobehub-icons.mjs.",
  `export const lobehubIconManifest = ${JSON.stringify(icons, null, 2)} as const;\n`,
].join("\n");
const expectedTargetEntries = [...sourceEntries, "__sprite.svg", "__sync-version.txt"].sort((left, right) =>
  left.localeCompare(right),
);
const isCurrent =
  existsSync(manifestFile) &&
  readFileSync(manifestFile, "utf8") === manifestContent &&
  existsSync(syncStampFile) &&
  readFileSync(syncStampFile, "utf8") === syncVersion &&
  hasExactEntries(targetDir, expectedTargetEntries);

if (!isCurrent) {
  rmSync(targetDir, { force: true, recursive: true });
  mkdirSync(targetDir, { recursive: true });
  cpSync(sourceDir, targetDir, { recursive: true });

  writeFileSync(
    spriteFile,
    [
      '<svg xmlns="http://www.w3.org/2000/svg" style="display:none">',
      ...iconFiles.map(buildSpriteSymbol),
      "</svg>\n",
    ].join("\n"),
  );

  mkdirSync(manifestDir, { recursive: true });
  writeFileSync(manifestFile, manifestContent);
  writeFileSync(syncStampFile, syncVersion);
}
