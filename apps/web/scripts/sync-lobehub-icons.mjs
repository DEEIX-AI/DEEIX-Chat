// Copies the LobeHub model icons from @lobehub/icons-static-svg into the static export and generates
// the icon index the app renders from.
//
// Icons are served one file per icon from a directory named after the package version, so the
// server can mark them immutable (see applyFrontendCacheHeaders in the backend) and a package
// upgrade changes every URL. Clients download only the icons they actually display.
//
// The index records each icon's tone, decided from the SVG source:
//   mono  — drawn only with currentColor; rendered as a CSS mask so it follows the text color.
//   color — fixed colors only; rendered as an image as is.
//   mixed — fixed colors plus currentColor parts (usually a wordmark); rendered as an image that is
//           inverted and hue-rotated in dark mode so the currentColor parts stay readable while the
//           brand hues are kept.
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptFile = fileURLToPath(import.meta.url);
const rootDir = dirname(dirname(scriptFile));
const packageDir = join(rootDir, "node_modules", "@lobehub", "icons-static-svg");
const sourceDir = join(packageDir, "icons");
const sourcePackageFile = join(packageDir, "package.json");
const targetDir = join(rootDir, "public", "vendor", "lobehub-icons");
const indexFile = join(rootDir, "shared", "generated", "lobehub-icons.ts");
const syncStampFile = join(targetDir, "__sync-version.txt");

const packageVersion = JSON.parse(readFileSync(sourcePackageFile, "utf8")).version;
if (!/^[0-9A-Za-z.+-]+$/u.test(packageVersion ?? "")) {
  throw new Error(`Unexpected @lobehub/icons-static-svg version: ${packageVersion}`);
}
const versionDir = join(targetDir, packageVersion);
const basePath = `/vendor/lobehub-icons/${packageVersion}`;
const syncVersion = createHash("sha256")
  .update(readFileSync(sourcePackageFile))
  .update(readFileSync(scriptFile))
  .digest("hex");

const PAINT_VALUE = /\b(?:fill|stroke|stop-color|color)\s*(?:=\s*["']|:\s*)([^"';>]+)/giu;
const NEUTRAL_PAINTS = new Set(["none", "currentcolor", "inherit", "transparent"]);

function iconTone(svg) {
  const usesCurrentColor = /currentColor/iu.test(svg);
  const usesFixedColor = /<(?:linearGradient|radialGradient|stop)\b/iu.test(svg) ||
    [...svg.matchAll(PAINT_VALUE)].some((match) => !NEUTRAL_PAINTS.has(match[1].trim().toLowerCase()));
  if (usesCurrentColor && !usesFixedColor) {
    return "mono";
  }
  return usesCurrentColor ? "mixed" : usesFixedColor ? "color" : "mono";
}

function hasExactEntries(directory, expectedEntries) {
  if (!existsSync(directory)) {
    return false;
  }
  const actualEntries = readdirSync(directory).sort((left, right) => left.localeCompare(right));
  return (
    actualEntries.length === expectedEntries.length &&
    actualEntries.every((entry, index) => entry === expectedEntries[index])
  );
}

const iconFiles = readdirSync(sourceDir)
  .filter((name) => name.endsWith(".svg"))
  .sort((left, right) => left.localeCompare(right));
const tones = Object.fromEntries(
  iconFiles.map((fileName) => [fileName.slice(0, -4), iconTone(readFileSync(join(sourceDir, fileName), "utf8"))]),
);
const slugsWithTone = (tone) => Object.keys(tones).filter((slug) => tones[slug] === tone).join(",");
// Comma-separated lists rather than an object: the index ships with every page that shows a model
// icon, and the lists are about a third smaller than the equivalent record.
const indexContent = [
  "// This file is generated by scripts/sync-lobehub-icons.mjs.",
  "",
  "/** URL prefix of the bundled LobeHub icons; versioned so the files can be cached as immutable. */",
  `export const LOBEHUB_ICON_BASE_PATH = ${JSON.stringify(basePath)};`,
  "",
  "/** Every bundled icon slug, comma-separated. */",
  `export const LOBEHUB_ICON_SLUGS = ${JSON.stringify(Object.keys(tones).join(","))};`,
  "",
  "/** Bundled icons with fixed colors only (see scripts/sync-lobehub-icons.mjs). */",
  `export const LOBEHUB_COLOR_ICON_SLUGS = ${JSON.stringify(slugsWithTone("color"))};`,
  "",
  "/** Bundled icons combining fixed colors with currentColor parts. */",
  `export const LOBEHUB_MIXED_ICON_SLUGS = ${JSON.stringify(slugsWithTone("mixed"))};`,
  "",
].join("\n");

const isCurrent =
  existsSync(indexFile) &&
  readFileSync(indexFile, "utf8") === indexContent &&
  existsSync(syncStampFile) &&
  readFileSync(syncStampFile, "utf8") === syncVersion &&
  hasExactEntries(targetDir, [packageVersion, "__sync-version.txt"].sort((left, right) => left.localeCompare(right))) &&
  hasExactEntries(versionDir, iconFiles);

if (!isCurrent) {
  rmSync(targetDir, { force: true, recursive: true });
  mkdirSync(versionDir, { recursive: true });
  for (const fileName of iconFiles) {
    cpSync(join(sourceDir, fileName), join(versionDir, fileName));
  }
  mkdirSync(dirname(indexFile), { recursive: true });
  writeFileSync(indexFile, indexContent);
  writeFileSync(syncStampFile, syncVersion);
}
