import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

const repository = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const version = "0.4.6-beta.1";

function fixture(t, { eol = "\n", name = "deeix-chat-desktop" } = {}) {
  const root = mkdtempSync(join(tmpdir(), "sync-version-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const write = (path, content) => {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), content.replace(/\r?\n/g, eol));
  };
  const read = (path) => readFileSync(join(root, path), "utf8");
  const lockPath = "apps/desktop/src-tauri/Cargo.lock";
  write("VERSION", `${version}\n`);
  for (const area of ["", "packages/api-contract/", "packages/core/", "apps/web/", "apps/desktop/", "backend/"]) {
    write(`${area}package.json`, `${JSON.stringify({ name: area || "root", version }, null, 2)}\n`);
  }
  write("backend/cmd/server/main.go", `package main\n// @version ${version}\n`);
  write("apps/desktop/src-tauri/tauri.conf.json", `${JSON.stringify({ version }, null, 2)}\n`);
  write("apps/desktop/src-tauri/Cargo.toml", `[package]\nname = "${name}"\nversion = "${version}"\n\n[dependencies]\nfixture = "1"\n`);
  const rootEntry = `[[package]]\nname = "${name}"\nversion = "0.4.5"\ndependencies = [\n "fixture",\n]\n`;
  write(lockPath, `# Generated by Cargo.\nversion = 3\n\n[[package]]\nname = "fixture"\nversion = "0.4.5"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "unchanged-dependency-checksum"\n\n${rootEntry}\n[[package]]\nname = "${name}"\nversion = "7.8.9"\nsource = "registry+https://github.com/rust-lang/crates.io-index"\nchecksum = "unchanged-same-name-checksum"\n`);
  const script = join(root, "scripts", "sync-version.mjs");
  mkdirSync(dirname(script), { recursive: true });
  copyFileSync(join(repository, "scripts", "sync-version.mjs"), script);
  const run = (...args) => spawnSync(process.execPath, [script, ...args], { cwd: root, encoding: "utf8" });
  return { root, write, read, run, lockPath, rootEntry: rootEntry.replace(/\n/g, eol), eol };
}

test("desktop version checks reject a stale Cargo root entry without changing it", (t) => {
  const f = fixture(t);
  const before = f.read(f.lockPath);
  const result = f.run("--check", "desktop");
  assert.notEqual(result.status, 0);
  assert.match(result.stderr, /VERSION is not synchronized with 1 file/);
  assert.match(result.stderr, /Cargo\.lock/);
  assert.match(result.stderr, /node scripts\/sync-version\.mjs desktop/);
  assert.equal(f.read(f.lockPath), before);
});

test("sync updates only the local package, preserving dependency pins and line endings", (t) => {
  for (const options of [{ eol: "\n" }, { eol: "\r\n", name: "renamed-desktop" }]) {
    const f = fixture(t, options);
    const before = f.read(f.lockPath);
    const result = f.run("desktop");
    assert.equal(result.status, 0, result.stderr);
    const expected = before.replace(f.rootEntry, f.rootEntry.replace('version = "0.4.5"', `version = "${version}"`));
    assert.equal(f.read(f.lockPath), expected);
    assert.equal(f.run("--check", "desktop").status, 0);
    assert.equal(f.run("desktop").status, 0);
    assert.equal(f.read(f.lockPath), expected, "a repeated sync is idempotent");
  }
});

test("the normal all-target version command also checks and synchronizes Cargo.lock", (t) => {
  const f = fixture(t);
  const check = f.run("--check");
  assert.notEqual(check.status, 0);
  assert.match(check.stderr, /Cargo\.lock/);
  assert.match(check.stderr, /Run: pnpm api:generate\s*$/);
  const sync = f.run();
  assert.equal(sync.status, 0, sync.stderr);
  assert.equal(f.run("--check").status, 0);
});

test("missing or ambiguous local package records fail without rewriting dependencies", (t) => {
  for (const duplicate of [false, true]) {
    const f = fixture(t);
    const before = f.read(f.lockPath);
    f.write(f.lockPath, duplicate ? before + `\n${f.rootEntry}` : before.replace(f.rootEntry, ""));
    const invalid = f.read(f.lockPath);
    const result = f.run("desktop");
    assert.notEqual(result.status, 0);
    assert.match(result.stderr, /Expected one local/);
    assert.equal(f.read(f.lockPath), invalid);
  }
});

test("version checks for other areas remain independent of the desktop lockfile", (t) => {
  const f = fixture(t);
  for (const area of ["workspace", "web", "backend"]) {
    const result = f.run("--check", area);
    assert.equal(result.status, 0, result.stderr);
  }
});
